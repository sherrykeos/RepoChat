package repochat.backend.security.crypto;

import java.nio.ByteBuffer;
import java.nio.charset.StandardCharsets;
import java.security.SecureRandom;
import java.security.spec.KeySpec;
import java.util.Base64;
import javax.crypto.Cipher;
import javax.crypto.SecretKey;
import javax.crypto.SecretKeyFactory;
import javax.crypto.spec.GCMParameterSpec;
import javax.crypto.spec.PBEKeySpec;
import javax.crypto.spec.SecretKeySpec;

import org.springframework.security.crypto.encrypt.Encryptors;
import org.springframework.security.crypto.encrypt.TextEncryptor;

/**
 * Modern authenticated token encryptor using AES-256-GCM with secure random 96-bit IVs.
 * Ciphertexts generated by this class are prefixed with "v2$".
 * Legacy ciphertexts without "v2$" are transparently decrypted using Spring's legacy Encryptors.text
 * to support zero-downtime, continuous migration of existing user credentials.
 */
public class VersionedTokenEncryptor implements TextEncryptor {

    public static final String V2_PREFIX = "v2$";
    private static final int GCM_IV_LENGTH_BYTES = 12; // 96 bits recommended for GCM
    private static final int GCM_TAG_LENGTH_BITS = 128; // 128-bit authentication tag
    private static final int PBKDF2_ITERATIONS = 65_536;
    private static final int KEY_LENGTH_BITS = 256;

    private final SecretKey secretKey;
    private final TextEncryptor legacyEncryptor;
    private final SecureRandom secureRandom;

    @SuppressWarnings("deprecation")
    public VersionedTokenEncryptor(String password, String salt) {
        if (password == null || password.isBlank()) {
            throw new IllegalArgumentException("Encryption password must not be null or blank");
        }
        if (salt == null || salt.isBlank()) {
            throw new IllegalArgumentException("Encryption salt must not be null or blank");
        }

        this.secureRandom = new SecureRandom();
        this.secretKey = deriveKey(password, salt);
        this.legacyEncryptor = Encryptors.text(password, salt);
    }

    @Override
    public String encrypt(String text) {
        if (text == null) {
            return null;
        }

        try {
            byte[] iv = new byte[GCM_IV_LENGTH_BYTES];
            secureRandom.nextBytes(iv);

            Cipher cipher = Cipher.getInstance("AES/GCM/NoPadding");
            GCMParameterSpec spec = new GCMParameterSpec(GCM_TAG_LENGTH_BITS, iv);
            cipher.init(Cipher.ENCRYPT_MODE, secretKey, spec);

            byte[] cipherText = cipher.doFinal(text.getBytes(StandardCharsets.UTF_8));

            ByteBuffer buffer = ByteBuffer.allocate(iv.length + cipherText.length);
            buffer.put(iv);
            buffer.put(cipherText);

            return V2_PREFIX + Base64.getUrlEncoder().withoutPadding().encodeToString(buffer.array());
        } catch (Exception ex) {
            throw new IllegalStateException("Failed to encrypt token with AES-GCM", ex);
        }
    }

    @Override
    public String decrypt(String encryptedText) {
        if (encryptedText == null || encryptedText.isBlank()) {
            return "";
        }

        // Modern AES-GCM format
        if (encryptedText.startsWith(V2_PREFIX)) {
            try {
                String payload = encryptedText.substring(V2_PREFIX.length());
                byte[] decoded = Base64.getUrlDecoder().decode(payload);

                int minLength = GCM_IV_LENGTH_BYTES + (GCM_TAG_LENGTH_BITS / 8);
                if (decoded.length < minLength) {
                    throw new IllegalArgumentException("Ciphertext payload too short for AES-GCM verification");
                }

                ByteBuffer buffer = ByteBuffer.wrap(decoded);
                byte[] iv = new byte[GCM_IV_LENGTH_BYTES];
                buffer.get(iv);

                byte[] cipherText = new byte[buffer.remaining()];
                buffer.get(cipherText);

                Cipher cipher = Cipher.getInstance("AES/GCM/NoPadding");
                GCMParameterSpec spec = new GCMParameterSpec(GCM_TAG_LENGTH_BITS, iv);
                cipher.init(Cipher.DECRYPT_MODE, secretKey, spec);

                byte[] plainText = cipher.doFinal(cipherText);
                return new String(plainText, StandardCharsets.UTF_8);
            } catch (Exception ex) {
                throw new IllegalStateException("Failed to decrypt token (authentication tag mismatch or corrupted ciphertext)", ex);
            }
        }

        // Transparent fallback to legacy decryptor for older records
        try {
            return legacyEncryptor.decrypt(encryptedText);
        } catch (Exception ex) {
            throw new IllegalStateException("Failed to decrypt legacy token", ex);
        }
    }

    private SecretKey deriveKey(String password, String salt) {
        try {
            byte[] saltBytes = parseSalt(salt);
            SecretKeyFactory factory = SecretKeyFactory.getInstance("PBKDF2WithHmacSHA256");
            KeySpec spec = new PBEKeySpec(password.toCharArray(), saltBytes, PBKDF2_ITERATIONS, KEY_LENGTH_BITS);
            byte[] keyBytes = factory.generateSecret(spec).getEncoded();
            return new SecretKeySpec(keyBytes, "AES");
        } catch (Exception ex) {
            throw new IllegalStateException("Could not derive cryptographic key from configured password and salt", ex);
        }
    }

    private byte[] parseSalt(String salt) {
        // If salt is hex-encoded, decode it; otherwise use raw UTF-8 bytes
        if (salt.length() % 2 == 0 && salt.matches("^[0-9a-fA-F]+$")) {
            byte[] bytes = new byte[salt.length() / 2];
            for (int i = 0; i < salt.length(); i += 2) {
                bytes[i / 2] = (byte) ((Character.digit(salt.charAt(i), 16) << 4)
                        + Character.digit(salt.charAt(i + 1), 16));
            }
            return bytes;
        }
        return salt.getBytes(StandardCharsets.UTF_8);
    }
}
